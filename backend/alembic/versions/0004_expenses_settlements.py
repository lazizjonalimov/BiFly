SETTLEMENTS_GUARD = """
CREATE FUNCTION driver_settlements_guard() RETURNS trigger LANGUAGE plpgsql AS
$$ BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status <> 'draft' THEN
      RAISE EXCEPTION 'Only a draft settlement can be deleted' USING ERRCODE = 'check_violation';
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.status <> 'draft' AND
     (NEW.earnings, NEW.reimbursements, NEW.deductions, NEW.net_pay, NEW.driver_id, NEW.period_start,
      NEW.period_end, NEW.number, NEW.currency)
     IS DISTINCT FROM
     (OLD.earnings, OLD.reimbursements, OLD.deductions, OLD.net_pay, OLD.driver_id, OLD.period_start,
      OLD.period_end, OLD.number, OLD.currency) THEN
    RAISE EXCEPTION 'An approved settlement cannot be changed' USING ERRCODE = 'check_violation';
  END IF;
  IF OLD.status IN ('paid', 'void') AND NEW.status <> OLD.status THEN
    RAISE EXCEPTION 'A paid or void settlement is final' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$
"""

LINES_GUARD = """
CREATE FUNCTION settlement_lines_guard() RETURNS trigger LANGUAGE plpgsql AS
$$ DECLARE parent_status text;
BEGIN
  SELECT status INTO parent_status FROM driver_settlements
  WHERE id = CASE WHEN TG_OP = 'DELETE' THEN OLD.settlement_id ELSE NEW.settlement_id END;
  -- parent_status is NULL while a draft is being deleted together with its lines
  IF parent_status IS NOT NULL AND parent_status <> 'draft' THEN
    RAISE EXCEPTION 'Lines of an approved settlement cannot be changed' USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$
"""

EXPENSES_GUARD = """
CREATE FUNCTION expenses_guard() RETURNS trigger LANGUAGE plpgsql AS
$$ DECLARE parent_status text;
BEGIN
  IF OLD.settlement_id IS NOT NULL THEN
    SELECT status INTO parent_status FROM driver_settlements WHERE id = OLD.settlement_id;
  END IF;
  IF parent_status IN ('approved', 'paid') THEN
    IF TG_OP = 'DELETE' OR
       (NEW.amount, NEW.category, NEW.driver_id, NEW.driver_treatment, NEW.incurred_on, NEW.currency,
        NEW.settlement_id)
       IS DISTINCT FROM
       (OLD.amount, OLD.category, OLD.driver_id, OLD.driver_treatment, OLD.incurred_on, OLD.currency,
        OLD.settlement_id) THEN
      RAISE EXCEPTION 'This expense is part of an approved settlement' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$
"""


